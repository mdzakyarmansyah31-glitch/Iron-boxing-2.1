export function buildCareerFighterProfile(career: CareerState): FighterProfile {
  const base =
    PLAYABLE_FIGHTERS.find((f) => f.id === career.fighterId) ?? PLAYABLE_FIGHTERS[0];
  return {
    ...base,
    name: career.customName || base.name,
    nickname: career.customNickname || base.nickname,
    stance: career.customStance || base.stance,
    appearance: career.customAppearance ? { ...career.customAppearance } : { ...base.appearance },
  };
}

